<?php

// 1. виведення тексту
echo "<h2>1. Hello, World!</h2>";

// виводимо текст на сторінку
echo "Hello, World!";


// 2. змінні та типи даних
echo "<h2>2. Змінні та типи даних</h2>";

// рядкова змінна
$name = "Діана";

// цілочисельна змінна
$age = 18;

// змінна з числом з плаваючою комою
$average = 89.5;

// булева змінна
$isStudent = true;

// вивід значення змінних
echo "Ім'я: $name<br>";
echo "Вік: $age<br>";
echo "Середній бал: $average<br>";
echo "Студент: ";
echo $isStudent ? "Так" : "Ні";
echo "<br><br>";

// виведення типів змінних за допомогою var_dump
echo "Тип змінної name: ";
var_dump($name);

echo "<br>Тип змінної age: ";
var_dump($age);

echo "<br>Тип змінної average: ";
var_dump($average);

echo "<br>Тип змінної isStudent: ";
var_dump($isStudent);

echo "<br>";


// 3. конкатенація рядків
echo "<h2>3. Конкатенація рядків</h2>";

// створення двох рядків
$firstName = "Діана";
$lastName = "Клищук";

// об'єднуємо два рядки за допомогою оператора .
$fullName = $firstName . " " . $lastName;

// виведення результата
echo "Повне ім'я: " . $fullName;

echo "<br>";


// 4. умовна конструкція
echo "<h2>4. Умовна конструкція if-else</h2>";

// створюємо змінну з числовим значенням
$number = 8;

// перевірка, чи є число парним
if ($number % 2 == 0) {
    echo "Число $number є парним.";
} else {
    echo "Число $number є непарним.";
}

echo "<br>";


// 5. цикли
echo "<h2>5. Цикли</h2>";

echo "Числа від 1 до 10 за допомогою for:<br>";

// цикл for виводить числа від 1 до 10
for ($i = 1; $i <= 10; $i++) {
    echo $i . " ";
}

echo "<br><br>";

echo "Числа від 10 до 1 за допомогою while:<br>";

// початкове значення лічильника
$i = 10;

// цикл while виводить числа від 10 до 1
while ($i >= 1) {
    echo $i . " ";
    $i--;
}

echo "<br>";


// 6. масиви
echo "<h2>6. Масиви</h2>";

// створюємо асоціативний масив з інформацією про студента
$student = [
    "ім'я" => "Діана",
    "прізвище" => "Клищук",
    "вік" => 18,
    "спеціальність" => "Комп'ютерні науки"
];

// виводимо кожен елнмент масиву
echo "Ім'я: " . $student["ім'я"] . "<br>";
echo "Прізвище: " . $student["прізвище"] . "<br>";
echo "Вік: " . $student["вік"] . "<br>";
echo "Спеціальність: " . $student["спеціальність"] . "<br>";

// додаємо середній бал до масиву
$student["середній бал"] = 89.5;

// виводимо оновлений масив
echo "<br>Оновлений масив студента:<br>";
echo "<pre>";
print_r($student);
echo "</pre>";

?>